-- انسخ هذا الملف كاملاً والصقه في: Supabase ← SQL Editor ← New query ← Run
--
-- **العطل** (اكتُشف 2026-08-27 أثناء اختبار الاستقطاعات):
--   جدول `payrolls` كان ينقصه عمود `journal_entry_id`، بينما المحفّز
--   `trg_payroll_ledger` ما زال يستدعي `repost_payroll()` التي تقرأ
--   `r.journal_entry_id`. فكانت **كل** محاولة لتوليد كشف راتب تفشل:
--       ERROR: record "r" has no field "journal_entry_id"
--
--   السبب الأرجح: إعادة إنشاء الجدول لاحقاً (drop … cascade في sql/012
--   أو تنظيف بيانات الاختبار) أسقطت العمود الذي أضافه sql/015، وبقيت
--   الدوال والمحفّزات تشير إليه.
--
-- الإصلاح إضافي بحت: يعيد العمود فيعود الترحيل المحاسبي للرواتب كما
-- صُمّم في sql/015. لا بيانات تتأثر (لم يكن أي كشف قابلاً للإنشاء).
--
-- ⚠️ درس: لا تُعِد إنشاء جدول بـ `drop … cascade` بعد أن أضافت ملفات
--    لاحقة أعمدة عليه — أو أعد تشغيل تلك الملفات بعده.
--
-- يتطلب: sql/011 و sql/012 و sql/015. آمن لإعادة التشغيل.
-- ============================================================

alter table public.payrolls
  add column if not exists journal_entry_id uuid
  references public.journal_entries(id) on delete set null;

notify pgrst, 'reload schema';
