-- انسخ هذا الملف كاملاً والصقه في: Supabase ← SQL Editor ← New query ← Run
--
-- ⚠️ هجرة **بيانات** لا بنية. لا جدول ولا عمود ولا دالّة ولا سياسة.
--    تُصحّح صفّاً واحداً بأمر المالك (2026-09-03).
--
-- ===== السبب =====
--
-- حجز الوحدة ٧٥ في مجمع الفرقان (العميل: عقيل عباس) كان مسجَّلاً
-- بمبلغ 77,180,000 في حقل `amount` — وهو حقل **مبلغ الحجز/العربون**.
-- والرقم ليس عربوناً، بل **ثمن الوحدة كاملاً**؛ وهو نفس مبلغ
-- الفاتورة INV-0002 حرفاً بحرف.
--
-- وتلال شركة تسويق ووساطة لا بائعة العقار: ثمن الوحدة لا يمرّ
-- بصندوقها ولا يخصّ دفاترها. فبقاء الرقم في هذا الحقل يجعل كل
-- تقرير عربونات وكل حساب قادم يقرأ ثمن وحدةٍ على أنه مالٌ مقبوض.
--
-- ⚠️ ولا أثر محاسبياً لهذا التصحيح: الحجز لم يكن له قيد أصلاً
--    (journal_entry_id فارغ)، وحساب 2400 عربونات محجوزة فيه صفر
--    سطور. فهذا تنظيف بيانات لا تصحيح حسابات، ولا يمسّ ميزاناً.
--
-- ===== ما لا تفعله هذه الهجرة =====
--   • لا تحذف الحجز — يبقى «بيع مكتمل» والوحدة «مباعة».
--   • لا تحذف الفاتورة INV-0002 — تبقى وثيقة متابعة للمشتري.
--   • لا تمسّ حجز الوحدة ٩٥ (عربون ياسر الشماع 5,000,000) — عربون
--     صحيح يبقى كما هو.
--   • لا تمسّ الحركات النقدية ولا القيود ولا الرواتب ولا
--     الاستقطاعات ولا العمولات.
--
-- ===== لماذا يُعطَّل محفّز واحد =====
--
-- تسعة محفّزات تُطلَق على تعديل هذا الصفّ. فُحصت واحداً واحداً:
--   sync_unit_from_reservation  مقيَّد بعمود status → لا يُطلَق
--   invoice_on_sale             يجد الفاتورة قائمة → يخرج
--   post_broker_commission      العميل بلا شركة وسيطة → يخرج
--   close_client_stage_on_sale  مرحلة العميل «بيع» أصلاً → يخرج
--   post_reservation_deposit    المبلغ صار فارغاً → لا قيد
--   guard_reservation_unit      فحوصه على INSERT فقط
--   reset_expiry_notice         expiry_date لم يتغيّر
--   clear_stale_sale_request    مقيَّد بعمود status → لا يُطلَق
--
--   on_sale_record_commission   ⚠️ يعمل، والحالة «بيع مكتمل»،
--       فيُنشئ صفّ sale_commissions **بنِسَب اليوم** لصفقةٍ تمّت
--       في 2026-08-31 — وهذا كسرٌ لمبدأ تجميد النِّسب وقت البيع.
--
-- فيُعطَّل هذا وحده أثناء الأمر ثم يُعاد فوراً، وكله في معاملة
-- واحدة فلا يبقى معطَّلاً إن فشل شيء.
--
-- جُرّبت في معاملة أُلغيت قبل التنفيذ، فبقي كل ما يجب أن يبقى:
--   حالة الحجز «بيع مكتمل» · الوحدة «مباعة» · وحدة ٩٥ بـ 5,000,000
--   sale_commissions = 0 · الفواتير = 1 · القيود = 52 · العمولات = 1
--
-- ===== التراجع =====
--   update public.reservations set amount = 77180000
--    where id = '10c291bb-6418-4071-9546-a9e869bff626';
--   (مع تعطيل نفس المحفّز، وإلا أُنشئ صفّ عمولة بنِسَب اليوم)
--
-- طُبّق على القاعدة في 2026-09-03 عبر هجرة:
--   clear_unit75_price_from_deposit_field
-- ============================================================

alter table public.reservations disable trigger trg_record_sale_commission;

update public.reservations
   set amount = null
 where id = '10c291bb-6418-4071-9546-a9e869bff626'
   and amount = 77180000;   -- شرطٌ يجعل إعادة التشغيل بلا أثر

alter table public.reservations enable trigger trg_record_sale_commission;
